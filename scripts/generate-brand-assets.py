#!/usr/bin/env python3
"""Export Carnet branding from Icon.svg. Requires Inkscape, no app dependency."""

from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
OUT = ROOT / "assets/branding"
SVG = ROOT / "Icon.svg"
NS = "{http://www.w3.org/2000/svg}"


def export_png(source, destination, size):
    subprocess.run([
        "inkscape", str(source), f"--export-filename={destination}",
        f"--export-width={size}", f"--export-height={size}",
    ], check=True, stdout=subprocess.DEVNULL)


def rect_path(node):
    x, y = float(node.get("x", 0)), float(node.get("y", 0))
    w, h = float(node.get("width")), float(node.get("height"))
    r = float(node.get("rx", 0))
    if r == 0:
        return f"M{x},{y} H{x+w} V{y+h} H{x} Z"
    return (f"M{x+r},{y} H{x+w-r} A{r},{r} 0 0 1 {x+w},{y+r} "
            f"V{y+h-r} A{r},{r} 0 0 1 {x+w-r},{y+h} H{x+r} "
            f"A{r},{r} 0 0 1 {x},{y+h-r} V{y+r} A{r},{r} 0 0 1 {x+r},{y} Z")


def vector_path(node):
    tag = node.tag.removeprefix(NS)
    fill = node.get("fill", "#000000")
    if fill == "white":
        fill = "#FFFFFF"
    if tag == "line":
        path = (f'<path android:pathData="M{node.get("x1")},{node.get("y1")} '
                f'L{node.get("x2")},{node.get("y2")}" '
                f'android:strokeColor="{node.get("stroke")}" '
                f'android:strokeWidth="{node.get("stroke-width")}" '
                'android:strokeLineCap="round" />')
    else:
        data = rect_path(node) if tag == "rect" else node.get("d")
        path = f'<path android:fillColor="{fill}" android:pathData="{data}" />'
    transform = node.get("transform")
    if transform:
        angle, x, y = transform.removeprefix("rotate(").removesuffix(")").split()
        path = (f'<group android:rotation="{angle}" android:pivotX="{x}" '
                f'android:pivotY="{y}">{path}</group>')
    return path


def write_vector(name, body, viewport, size):
    (RES / "drawable" / name).write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate-brand-assets.py from Icon.svg. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        f'android:width="{size}dp" android:height="{size}dp" '
        f'android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
        f'{body}\n</vector>\n'
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    source = SVG.read_text()
    nodes = list(ET.fromstring(source))
    write_vector("ic_carnet_logo.xml", "\n".join(map(vector_path, nodes)), 341, 32)

    # Centre the paper mark inside the adaptive icon's 66dp safe zone.
    group = '<group android:scaleX="0.25" android:scaleY="0.25" android:translateX="9.5" android:translateY="11.375">'
    write_vector("ic_carnet_foreground.xml", group + "\n".join(map(vector_path, nodes[1:])) + "</group>", 108, 108)

    # A real single-colour mark with transparent details for Android themed icons.
    # The secondary paper is omitted to keep the small monochrome silhouette legible.
    holes = [rect_path(nodes[2]), nodes[3].get("d")]
    for node in nodes[4:]:
        if node.tag == NS + "line":
            holes.append(rect_path(ET.Element("rect", {
                "x": str(float(node.get("x1")) - 4),
                "y": str(float(node.get("y1")) - 4),
                "width": str(float(node.get("x2")) - float(node.get("x1")) + 8),
                "height": "8", "rx": "4",
            })))
        else:
            holes.append(node.get("d"))
    mono = '<group android:translateX="17.5">' + '<path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="' + " ".join(holes) + '" /></group>'
    write_vector("ic_carnet_monochrome.xml", group + mono + "</group>", 108, 108)

    export_png(SVG, OUT / "play-store-icon.png", 512)
    for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        export_png(SVG, RES / f"mipmap-{density}" / "ic_launcher.png", size)


if __name__ == "__main__":
    main()
